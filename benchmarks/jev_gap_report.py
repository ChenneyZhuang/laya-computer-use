"""Gap report generator: how far is each model from the commercial reference?

The user's question was "how big is the gap to official Jev, and is EVERY official
Laya model this bad". This script answers both with one artifact:

1. Runs the arena core suite for each available contender.
2. Prints a comparison table (Jev's row is the reference line).
3. Splits out the Laya family to answer the "are they all bad?" question directly.
4. Writes `private/JEV_GAP_REPORT.md` — the user's private copy, never pushed.

    python3 -m benchmarks.jev_gap_report            # available contenders
    python3 -m benchmarks.jev_gap_report jev von laya-en
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "benchmarks" / "results"
PRIVATE = ROOT / "private"

sys.path.insert(0, str(ROOT))
for _candidate in (ROOT.parent / "localdecide", Path("/Volumes/SSD/localdecide")):
    if (_candidate / "localdecide").is_dir():
        sys.path.insert(0, str(_candidate))
        break


def collect(names: list[str], suite: str = "core") -> dict[str, dict]:
    """Run each contender in a child process; keep the JSON that child wrote."""
    import subprocess

    from benchmarks.model_arena import CONTENDERS

    summary: dict[str, dict] = {}
    for name in names:
        spec = CONTENDERS[name]
        print(f"-- {name} ...", flush=True)
        import os

        env = dict(os.environ, ARENA_CHILD=name, ARENA_KIND=spec["kind"],
                   ARENA_SPEC=json.dumps(spec), ARENA_SUITE=suite)
        executable = sys.executable
        if spec["kind"] == "von":
            candidate = Path("/Volumes/SSD/lcu-experiments/von-env/bin/python")
            if candidate.exists():
                executable = str(candidate)
        proc = subprocess.run([executable, str(ROOT / "benchmarks" / "model_arena.py"), "--child"],
                              capture_output=True, text=True, timeout=3600, env=env)
        if proc.returncode != 0:
            print(f"   FAILED rc={proc.returncode}: {proc.stderr[-300:]}")
            summary[name] = {"error": proc.stderr[-300:]}
            continue
        stdout = proc.stdout
        payload = json.loads(stdout[stdout.find("{"):])
        (RESULTS / f"arena_{name}.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2))
        summary[name] = payload
        print(f"   {payload['hits']}/{payload['cases']} ({payload['accuracy']:.0%}), "
              f"{payload['median_ms']} ms")
    return summary


def render(summary: dict[str, dict], suite: str) -> str:
    lines: list[str] = []
    lines.append("# Model gap report — desktop control selection")
    lines.append("")
    lines.append("Generated by `benchmarks/jev_gap_report.py`. Private: do not publish.")
    lines.append(f"Suite: `{suite}` — the same element table and the same typed questions")
    lines.append("for every contender; only the model behind `Decider` changes.")
    lines.append("")

    jev = summary.get("jev") or {}
    jev_hits = jev.get("hits")
    jev_cases = jev.get("cases")

    lines.append("## Contenders")
    lines.append("")
    lines.append("| model | kind | hits | accuracy | median ms | vs Jev |")
    lines.append("|---|---|---|---|---|---|")
    order = ["jev", "von", "laya-en", "laya-multilingual", "laya-typed-decisions"]
    for name in order + [k for k in summary if k not in order]:
        if name not in summary:
            continue
        row = summary[name]
        if "error" in row and "hits" not in row:
            lines.append(f"| {name} | — | — | failed | — | {row['error'][:60]} |")
            continue
        delta = ""
        if jev_hits is not None and row.get("hits") is not None:
            delta = f"{row['hits'] - jev_hits:+d} cases"
        lines.append(f"| {name} | {row.get('kind', '')} | {row.get('hits')}/{row.get('cases')} | "
                     f"{row.get('accuracy', 0):.0%} | {row.get('median_ms', '')} | {delta} |")
    lines.append("")

    # The "is every official Laya model this bad" question, answered directly.
    laya_rows = {k: v for k, v in summary.items() if k.startswith("laya-") and "hits" in v}
    if laya_rows:
        lines.append("## Are all official Laya checkpoints this bad?")
        lines.append("")
        total_hits = sum(v["hits"] for v in laya_rows.values())
        total_cases = sum(v["cases"] for v in laya_rows.values())
        lines.append(f"Across {len(laya_rows)} official checkpoint(s): {total_hits}/{total_cases}.")
        lines.append("")
        lines.append("| checkpoint | hits | reading |")
        lines.append("|---|---|---|")
        for name, row in laya_rows.items():
            reading = ("no control selection at all" if row["hits"] == 0
                       else f"picks {row['hits']} of {row['cases']}")
            lines.append(f"| {name} | {row['hits']}/{row['cases']} | {reading} |")
        lines.append("")
        if total_hits == 0:
            lines.append("Zero hits is not a measurement artifact: the fairness controls")
            lines.append("(option scaling 1→22, v1/v3 layouts, four phrasings, 30-trial")
            lines.append("position control) all rule out the obvious confounds, and the same")
            lines.append("checkpoints score well on their designed classification tasks.")
            lines.append("The gap is the task format, not a broken download.")
        lines.append("")

    if jev_hits is not None:
        lines.append("## Gap to Jev")
        lines.append("")
        lines.append(f"Jev (commercial reference): **{jev_hits}/{jev_cases}**.")
        for name, row in summary.items():
            if name == "jev" or "hits" not in row:
                continue
            lines.append(f"- {name}: {row['hits'] - jev_hits:+d} cases "
                         f"({row['hits']}/{row['cases']} vs {jev_hits}/{jev_cases})")
        lines.append("")

    lines.append("## Per-case detail")
    lines.append("")
    ids = []
    for row in summary.values():
        if "rows" in row:
            for case in row["rows"]:
                if case["id"] not in ids:
                    ids.append(case["id"])
    lines.append("| case | " + " | ".join(summary.keys()) + " |")
    lines.append("|" + "---|" * (len(summary) + 1))
    for case_id in ids:
        cells = []
        for row in summary.values():
            found = next((c for c in row.get("rows", []) if c["id"] == case_id), None)
            if found is None:
                cells.append("—")
            elif found.get("hit"):
                cells.append("✅")
            elif found.get("error"):
                cells.append(f"err: {str(found['error'])[:24]}")
            else:
                cells.append(f"✗ {found.get('operation', '')}")
        lines.append(f"| {case_id} | " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    names = args or ["jev", "laya-en", "laya-multilingual", "laya-typed-decisions", "von"]
    summary = collect(names)
    report = render(summary, "core")
    PRIVATE.mkdir(parents=True, exist_ok=True)
    (PRIVATE / "JEV_GAP_REPORT.md").write_text(report, encoding="utf-8")
    (RESULTS / "gap_summary.json").write_text(json.dumps(
        {k: {kk: vv for kk, vv in v.items() if kk != "rows"} for k, v in summary.items()},
        ensure_ascii=False, indent=2))
    print()
    print(report)


if __name__ == "__main__":
    main()
